// 计分与类型判定
function computeResult(answers) {
  const sum = { E: 0, R: 0, A: 0, P: 0 };
  QUESTIONS.forEach((q, i) => { sum[q.dim] += q.scores[answers[i]]; });
  const pct = {};
  ['E', 'R', 'A', 'P'].forEach(k => { pct[k] = Math.round(sum[k] / 24 * 100); });

  let key;
  if (pct.P >= 70 && pct.A <= 45) key = 'gongjiang';
  else if (pct.A <= 40) key = 'wugui';
  else if (pct.E >= 50 && pct.R >= 50) key = 'huojian';
  else if (pct.E >= 50 && pct.R < 50) key = 'taiyang';
  else if (pct.E < 50 && pct.R >= 50) key = 'leida';
  else key = 'nuanlu';

  // 副色：排除主类型判定所用维度，取偏离50最大的维度
  const used = key === 'gongjiang' ? ['P', 'A'] : key === 'wugui' ? ['A'] : ['E', 'R'];
  const cands = ['E', 'R', 'A', 'P'].filter(k => !used.includes(k));
  let subDim = cands[0];
  cands.forEach(k => { if (Math.abs(pct[k] - 50) > Math.abs(pct[subDim] - 50)) subDim = k; });

  let subKey;
  if (subDim === 'E') subKey = pct.E >= 50 ? 'mada' : 'anjing';
  else if (subDim === 'R') subKey = pct.R >= 50 ? 'tianxian' : 'wending';
  else if (subDim === 'A') subKey = pct.A >= 50 ? 'tanxian' : 'manre';
  else subKey = pct.P >= 50 ? 'guzhi' : 'suixing';

  return { key, subKey, pct, result: RESULTS[key], sub: SUBS[subKey] };
}
